/* Build the source-listed Tagalog verb-lemma expansion from Wiktionary. */
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const projectRoot = path.resolve(__dirname, "..");
const outputPath = path.join(projectRoot, "wiktionary-verbs.js");
const categoryUrl = new URL("https://en.wiktionary.org/w/api.php");
categoryUrl.search = new URLSearchParams({
  action: "query",
  list: "categorymembers",
  cmtitle: "Category:Tagalog_verbs",
  cmtype: "page",
  cmlimit: "500",
  format: "json"
});

function existingRoots() {
  const context = vm.createContext({
    window: {},
    document: { addEventListener() {} },
    navigator: {},
    console,
    setTimeout,
    clearTimeout
  });
  for (const filename of ["attestation.js", "verbs.js", "essential-verbs.js", "everyday-verbs.js", "lexicon.js", "app.js"]) {
    vm.runInContext(fs.readFileSync(path.join(projectRoot, filename), "utf8"), context, { filename });
  }
  return {
    roots: new Set(vm.runInContext("Object.keys(VERB_LEXICON)", context)),
    forms: new Set(vm.runInContext("Object.keys(ACTIVE_CONJUGATED_LOOKUP)", context))
  };
}

async function categoryMembers() {
  const titles = [];
  let continuation = null;
  do {
    const url = new URL(categoryUrl);
    if (continuation) url.searchParams.set("cmcontinue", continuation);
    const response = await fetch(url);
    if (!response.ok) throw new Error(`Wiktionary request failed: ${response.status}`);
    const body = await response.json();
    titles.push(...body.query.categorymembers.map(item => item.title));
    continuation = body.continue && body.continue.cmcontinue;
  } while (continuation);
  return titles;
}

async function main() {
  const { roots, forms } = existingRoots();
  const selected = (await categoryMembers())
    .filter(title => /^[a-z-]+$/.test(title))
    .filter(title => !roots.has(title) && !forms.has(title))
    .slice(0, 1000);
  if (selected.length !== 1000) throw new Error("Wiktionary did not yield 1,000 new Tagalog verb lemmas.");

  const source = `/* Generated by tools/build-wiktionary-verb-expansion.js. */\n\nconst WIKTIONARY_VERB_LEMMA_EXPANSION = Object.freeze(Object.fromEntries(\n  ${JSON.stringify(selected)}.map(root => [root, Object.freeze({\n    root,\n    meanings: [\`Tagalog verb lemma: \${root}\`],\n    allowedPatterns: [],\n    overrides: {\n      \"Dictionary lemma\": {\n        focus: \"Dictionary verb lemma\",\n        description: \"Source-listed Tagalog verb lemma. Focus and aspect forms await individual curation.\",\n        forms: {\n          infinitive: {\n            form: root,\n            use: \"Dictionary-listed verb lemma\",\n            example: \`\${root}. — Tagalog verb lemma.\`\n          }\n        }\n      }\n    },\n    examples: [],\n    status: \"reference\",\n    sources: [\n      { title: \"Wiktionary: Category:Tagalog verbs\", url: \"https://en.wiktionary.org/wiki/Category:Tagalog_verbs\" }\n    ],\n    notes: \"Source-listed verb lemma; its complete paradigm has not yet been individually reviewed.\"\n  })])\n));\n`;
  fs.writeFileSync(outputPath, source);
  console.log(`Wrote ${selected.length} source-listed Tagalog verb lemmas to ${path.basename(outputPath)}.`);
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
